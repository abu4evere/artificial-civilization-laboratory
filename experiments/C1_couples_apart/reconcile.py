"""C1 — put F1's and F2's "apart" figures on C1's footing. F1 and F2 report the share of ALL woman-weeks (16-45) in which
the first failing conception condition was "apart"; C1 reports the share of couple-weeks (woman 16-45 with a living
partner). Here F1's and F2's records are re-expressed per couple: apart ÷ (woman-weeks with a living partner who is not
pregnant), since "apart" is only checked for those.

  python experiments/C1_couples_apart/reconcile.py
"""
import json
from collections import Counter
from pathlib import Path

EXP = Path(__file__).parent.parent
SEEDS = tuple(range(501, 517)) + tuple(range(601, 617)) + tuple(range(811, 819)) + tuple(range(1101, 1125))


def per_couple(out, years=None):
    n = Counter()
    for s in SEEDS:
        r = json.loads((out / f"seed_{s}.json").read_text(encoding="utf-8"))
        for y, v in r["years"].items():
            if years is None or int(y) < years:
                n.update({k: x for k, x in v.items() if k == "woman_weeks" or k.startswith("r_")})
    ww = n["woman_weeks"]
    partnered = ww - n["r_no_partner"] - n["r_partner_dead"]
    checked = partnered - n["r_pregnant"]
    return ww, n["r_apart"] / ww, partnered / ww, n["r_apart"] / checked


lines = ["# Apart, per couple: F1 and F2 re-expressed (generated by `reconcile.py`)\n",
         "| run | window | share of all woman-weeks apart (as reported) | share of woman-weeks partnered | apart, per partnered non-pregnant woman-week |",
         "|---|---|---|---|---|"]
for name, out in (("F1 (control)", EXP / "F1_baseline_fragility" / "output"), ("F2 (perfect finding)", EXP / "F2_perfect_search" / "output")):
    for win, yrs in (("all years", None), ("years 0-39", 40)):
        ww, a, p, c = per_couple(out, yrs)
        lines.append(f"| {name} | {win} | {a:.1%} | {p:.1%} | **{c:.1%}** |")
text = "\n".join(lines) + "\n"
(Path(__file__).parent / "reconcile.md").write_text(text, encoding="utf-8")
print(text)
