"""C1 analysis, in the order of questions.md (frozen as `C1-questions`). Written before any discovery data was read.

  python experiments/C1_couples_apart/analyse_c1.py discovery   (or: holdout)
"""
from __future__ import annotations

import json
import statistics
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from run_c1 import DISCOVERY, HOLDOUT, OUT  # noqa: E402


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "–"


def main(which, out=OUT, seeds=None, write=True):
    seeds = seeds or (DISCOVERY if which == "discovery" else HOLDOUT)
    R = [json.loads((out / f"seed_{s}.json").read_text(encoding="utf-8")) for s in seeds]
    n = Counter()
    spells = []
    for r in R:
        n.update(r["n"])
        spells += r["spells"]
    L = []
    w = L.append
    w(f"# C1 — Why couples drift apart: {which} results (generated by `analyse_c1.py {which}`)\n")
    w("## Validity\n")
    checks = (out / "checks.txt").read_text(encoding="utf-8")
    rep = [r["seed"] for r in R if r.get("reproduces") is False]
    w(f"- Observer read-only: **{'yes' if 'CHANGES' not in checks and checks.count('READ-ONLY') >= 2 else 'NO'}**")
    w(f"- Replays reproduce F1's populations for the decades run: **{'yes' if not rep else 'NO: ' + str(rep)}**")
    w(f"- Code unchanged: **{'yes' if all(r['code_hash'] == r['code_hash_after'] for r in R) else 'NO'}**\n")
    w("## Population (beside every measure)\n")
    w("| seed | population at years 10, 20, 30, 40 |")
    w("|---|---|")
    for r in R:
        w(f"| {r['seed']} | {r['pops']} |")
    cw, ap = n["couple_weeks"], n["apart"]
    w(f"\nCouple-weeks (woman 16–45, partner alive): {cw:,}; apart (more than 2 tiles): {ap:,} (**{pct(ap, cw)}**).\n")

    w("## Q1. How far apart, and for how long\n")
    w("| distance when apart | couple-weeks | share of apart weeks |")
    w("|---|---|---|")
    for b in ("3", "4-6", "7+"):
        w(f"| {b} tiles{' (the gap: no conception, no pull)' if b == '3' else ''} | {n['dist|' + b]:,} | "
          f"{pct(n['dist|' + b], ap)} |")
    if spells:
        sp = sorted(spells)
        w(f"\nApart spells: {len(sp):,}; median length {statistics.median(sp)} week(s); one week {pct(sum(1 for x in sp if x == 1), len(sp))}; "
          f"longer than 13 weeks {pct(sum(1 for x in sp if x > 13), len(sp))}; weeks in spells longer than 13: "
          f"{pct(sum(x for x in sp if x > 13), sum(sp))} of all apart weeks.\n")

    w("## Q2. Who moves away, and doing what (together → apart)\n")
    sp_ = n["split"]
    w(f"Splits: {sp_:,}. Who moved: " + ", ".join(f"{k} {pct(n['split_who|' + k], sp_)}" for k in ("woman", "man", "both", "none")) + ".\n")
    acts = Counter({k.split("|")[1]: v for k, v in n.items() if k.startswith("split_action|")})
    tot = sum(acts.values())
    w("| action of the partner who moved | share of moves |")
    w("|---|---|")
    for a, v in acts.most_common():
        w(f"| {a} | {pct(v, tot)} |")

    w("\n## Q3. Beyond reach (more than 3 tiles): is the pull there, and what beats it\n")
    bp = n["beyond_pw"]
    w(f"Partner-weeks beyond reach: {bp:,}. A \"join\" option among the four top-scored: **{pct(n['beyond_join_top4'], bp)}**. "
      f"Mean affection for the partner {n['beyond_aff_sum'] / bp if bp else 0:.2f}; mean hunger {n['beyond_hunger_sum'] / bp if bp else 0:.2f}.\n")
    acts = Counter({k.split("|")[1]: v for k, v in n.items() if k.startswith("beyond_chosen|")})
    tot = sum(acts.values())
    w("| action chosen instead (or join) | share |")
    w("|---|---|")
    for a, v in acts.most_common():
        w(f"| {a} | {pct(v, tot)} |")

    w("\n## Q4. How couples come back together (apart → together)\n")
    acts = Counter({k.split("|")[1]: v for k, v in n.items() if k.startswith("rejoin_action|")})
    tot = sum(acts.values())
    w(f"Rejoins: {n['rejoin']:,}.\n")
    w("| action of the partner who closed the gap | share of moves |")
    w("|---|---|")
    for a, v in acts.most_common():
        w(f"| {a} | {pct(v, tot)} |")

    w("\n## Q5. Who is apart more\n")
    w("| group | couple-weeks | apart |")
    w("|---|---|---|")
    groups = sorted({k.split("|", 1)[1] for k in n if k.startswith("cw|")})
    for g in groups:
        w(f"| {g} | {n['cw|' + g]:,} | {pct(n['ap|' + g], n['cw|' + g])} |")
    w("\n(kids: the woman has a dependant under 6; season 0 spring … 3 winter; years: since the pairing was observed; "
      "aff: her affection for him.)")
    text = "\n".join(L) + "\n"
    if write:
        (HERE / f"results_{which}.md").write_text(text, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "discovery")
