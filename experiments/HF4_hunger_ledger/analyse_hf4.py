"""HF4 analysis with the frozen decision rule (questions.md, `HF4-questions`). Written before any data.

Operational details written with this file, before data:
- Coverage = food held just before eating ÷ need (need after any fire saving), adult-weeks only.
- A starving week is the code's own: shortfall above 5% of need (logged directly).
- r = H's median coverage ÷ C's, medians read from 0.01-wide histograms.
- Shifted prediction: the share of C's adult-weeks whose coverage × r falls below 0.95, read from C's histogram (bins
  whose upper edge × r < 0.95 count in full; the bin straddling the line counts in proportion).
- "H's extra starving weeks mostly deep": H's share of starving weeks with coverage < 0.5 exceeds C's.

  python experiments/HF4_hunger_ledger/analyse_hf4.py discovery   (or: holdout, or: both)
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from run_hf4 import BIN, DISCOVERY, HOLDOUT, NBINS, OUT  # noqa: E402


def f(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def div(a, b):
    return a / b if b else None


def pooled(arm, seeds, out):
    n, hist, R = Counter(), [0] * NBINS, []
    for s in seeds:
        r = json.loads((out / f"{arm}_seed_{s}.json").read_text(encoding="utf-8"))
        n.update(r["n"])
        hist = [a + b for a, b in zip(hist, r["hist"])]
        R.append(r)
    return n, hist, R


def median(hist):
    total, acc = sum(hist), 0
    for i, v in enumerate(hist):
        if acc + v >= total / 2:
            return (i + ((total / 2 - acc) / v if v else 0.5)) * BIN
        acc += v
    return None


def shifted_share(hist, r):
    """Share of entries whose coverage × r < 0.95."""
    total = sum(hist)
    line = 0.95 / r
    k = 0.0
    for i, v in enumerate(hist):
        lo, hi = i * BIN, (i + 1) * BIN
        if hi <= line:
            k += v
        elif lo < line:
            k += v * (line - lo) / BIN
    return k / total if total else None


def section(name, seeds, out, L):
    w = L.append
    nh, hh, RH = pooled("h", seeds, out)
    nc, hc, RC = pooled("c", seeds, out)
    ok = all(r.get("reproduces") is not False and r["code_hash"] == r["code_hash_after"] for r in RH + RC)
    w(f"## {name} (seeds {seeds[0]}–{seeds[-1]}, first 40 years)\n")
    w(f"Replays reproduce saved runs (where saved) and code unchanged: **{'yes' if ok else 'NO'}**. Adult-weeks: "
      f"H {nh['aw']:,}, C {nc['aw']:,}. Populations: " + "; ".join(f"{a['seed']} H{a['pops']} C{b['pops']}" for a, b in zip(RH, RC)) + ".\n")
    mh, mc = median(hh), median(hc)
    r = div(mh, mc)
    sh, sc = div(nh["starving"], nh["aw"]), div(nc["starving"], nc["aw"])
    pred = shifted_share(hc, r) if r else None
    deep_h, deep_c = div(nh["starving_deep"], nh["starving"]), div(nc["starving_deep"], nc["starving"])
    w("| measure | H (home base) | C (control) | H ÷ C |")
    w("|---|---|---|---|")
    w(f"| median coverage (food held ÷ need, at eating) | {f(mh)} | {f(mc)} | {f(r)} |")
    for lab, k in (("< 0.5", "lt05"), ("0.5–0.95", "05_095"), ("0.95–1.05", "095_105"), ("1.05–1.5", "105_15"),
                   ("1.5–3", "15_3"), ("≥ 3", "ge3")):
        a, b = div(nh[f"band_{k}"], nh["aw"]), div(nc[f"band_{k}"], nc["aw"])
        w(f"| share of adult-weeks with coverage {lab} | {f(a)} | {f(b)} | {f(div(a, b)) if a is not None and b else '–'} |")
    w(f"| starving share of adult-weeks (actual) | {f(sh)} | {f(sc)} | {f(div(sh, sc))} |")
    w(f"| share of starving weeks that are deep (coverage < 0.5) | {f(deep_h)} | {f(deep_c)} | {f(div(deep_h, deep_c))} |")
    w(f"| carers: share of food given to dependants just before eating | {f(div(nh['fed_share_sum'], nh['carer_weeks']))} | "
      f"{f(div(nc['fed_share_sum'], nc['carer_weeks']))} | – |")
    near = div(nc["band_095_105"] + nc["band_105_15"], nc["aw"])
    w(f"\nC adult-weeks near the line (coverage 0.95–1.5): {f(near)}. **Shifted prediction** (C's coverage × r = "
      f"{f(r)}): starving share {f(pred)} against H's actual {f(sh)} (ratio {f(div(pred, sh))}).\n")
    small = r is not None and r >= 0.9 and pred is not None and sh and abs(pred / sh - 1) <= 0.25
    tail = pred is not None and sh and pred < 0.75 * sh and deep_h is not None and deep_c is not None and deep_h > deep_c
    return small, tail, ok


def main(which="both", out=OUT, write=True):
    L = ["# HF4 — The hunger ledger: results (generated by `analyse_hf4.py`)\n"]
    z = (out / "zero.txt").read_text(encoding="utf-8")
    L.append(f"The log changes nothing (state hash equals HB1's code, both arms, two seeds): **{'yes' if 'All: PASS' in z else 'NO'}**.\n")
    sets = {"discovery": [("discovery", DISCOVERY)], "holdout": [("holdout", HOLDOUT)],
            "both": [("discovery", DISCOVERY), ("holdout", HOLDOUT)]}[which]
    res = {name: section(name, seeds, out, L) for name, seeds in sets}
    if len(res) == 2:
        (sd, td, okd), (sh_, th, okh) = res["discovery"], res["holdout"]
        L.append("## Frozen decision rule\n")
        if sd and sh_:
            v = "**Small shifts explain the hunger.**"
        elif td and th:
            v = "**A tail, not a shift.**"
        else:
            v = "**Mixed**; reported as such, the creator decides."
        L.append(f"Small shifts: discovery {'yes' if sd else 'no'}, holdout {'yes' if sh_ else 'no'}. Tail: discovery "
                 f"{'yes' if td else 'no'}, holdout {'yes' if th else 'no'}. Verdict: {v}")
        if not (okd and okh):
            L.append("\n**A hard stop was hit: recorded, not interpreted.**")
    text = "\n".join(L) + "\n"
    if write:
        (HERE / f"results_{which}.md").write_text(text, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "both")
