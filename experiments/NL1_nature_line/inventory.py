"""NL1 inventory (read-only): the register of ACL's settings with their recorded provenance, and a count of the fixed
decimal numbers inside the nature code's formulas. Writes register.md beside this file.

  python experiments/NL1_nature_line/inventory.py
"""
import datetime
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).parent
MODULES = ("mind", "biology", "actions", "social", "information", "knowhow", "thought", "inquiry", "marks", "weather",
           "fauna", "matter")
KIND = {  # a coarse grouping by what the setting governs (judgement, written here)
    "operational": {"seed", "width", "height", "founders", "stage"},
    "body": {"founder_min_age", "founder_max_age", "need_infant", "need_child", "need_teen", "need_adult", "need_elder",
             "starvation_damage", "fed_recovery", "cold_damage", "thirst_damage", "water_reach", "illness_chance",
             "illness_damage", "illness_recovery", "mortality_base", "mortality_rate", "energy_recovery", "fertile_from",
             "fertile_until", "conception_chance", "pregnancy_weeks", "nursing_weeks", "birth_death_chance", "mutation",
             "carry_limit", "material_limit", "item_limit", "reach", "perception"},
    "mind": {"choice_temperature", "learning_rate", "discount", "learned_weight", "association_rate", "worth_weight",
             "novelty", "memory_capacity", "mark_chance", "imitation_rate", "skill_gain", "camp_radius"},
}


def kind(name):
    for k, v in KIND.items():
        if name in v:
            return k
    return "world"


def main():
    src = (ROOT / "acl" / "config.py").read_text(encoding="utf-8").split("\n")
    blame = subprocess.run(["git", "blame", "--line-porcelain", "acl/config.py"], cwd=ROOT, capture_output=True,
                           text=True, encoding="utf-8").stdout
    line_commit, times, cur = {}, {}, None
    for l in blame.split("\n"):
        m = re.match(r"^([0-9a-f]{40}) \d+ (\d+)", l)
        if m:
            cur = (m[1], int(m[2]))
        elif l.startswith("author-time ") and cur:
            times[cur[0]] = int(l.split()[1])
        elif l.startswith("\t") and cur:
            line_commit[cur[1]] = cur[0]
    rows = []
    for i, l in enumerate(src, 1):
        m = re.match(r"\s+([a-z_]+): [^=]+= ([^#]+?)\s*(#\s*(.*))?$", l)
        if m:
            c = line_commit.get(i, "")
            day = datetime.date.fromtimestamp(times[c]).isoformat() if c in times else "?"
            rows.append((m[1], m[2].strip(), kind(m[1]), (m[4] or "").strip(), day, c[:7]))
    counts = {}
    for mod in MODULES:
        text = [l for l in (ROOT / "acl" / f"{mod}.py").read_text(encoding="utf-8").split("\n")
                if not l.strip().startswith("#")]
        counts[mod] = sum(len(re.findall(r"(?<![\w.])\d+\.\d+", l)) for l in text)
    out = ["# NL1 register: ACL's settings (`acl/config.py`) and their provenance", "",
           "Generated by `inventory.py` (read-only). **Source** is the evidence that set the value; none is recorded for "
           "any setting, so every row is **unanchored** until a source is added.", "",
           f"{len(rows)} settings. First recorded in git: " + ", ".join(sorted({r[4] for r in rows})) + ".", "",
           "| setting | value | governs | the code's own comment | first in git | source |", "|---|---|---|---|---|---|"]
    out += [f"| `{n}` | `{v}` | {k} | {cm} | {d} ({c}) | none recorded |" for n, v, k, cm, d, c in rows]
    out += ["", "## Fixed decimal numbers inside the nature code's formulas (not settings)", "",
            "| module | count |", "|---|---|"] + [f"| `acl/{m}.py` | {n} |" for m, n in counts.items()]
    out += [f"| **total** | **{sum(counts.values())}** |", "",
            "Counted as decimal literals outside comments (a coarse count: repeats and display values included)."]
    (HERE / "register.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    by = {}
    for r in rows:
        by[r[2]] = by.get(r[2], 0) + 1
    print(len(rows), "settings", by, "constants", sum(counts.values()))


if __name__ == "__main__":
    main()
