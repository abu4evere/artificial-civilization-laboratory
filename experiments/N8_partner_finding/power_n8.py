"""N8 — power calculation (method fixed in questions.md before computing).

Each world i has an extinction probability q_i ~ Beta(a, b), with mean = the control's extinction share and spread set so
that two independent histories disagree as often as the sham disagrees with the control. A treatment multiplies q_i by
(1 - e). Power = share of simulated experiments where the exact two-sided sign test on discordant worlds gives p < 0.05
with fewer extinctions in the treatment.

  python experiments/N8_partner_finding/power_n8.py      -> power.md
"""
from __future__ import annotations

import json
import random
from math import comb
from pathlib import Path

HERE = Path(__file__).parent
EXP = HERE.parent
SEEDS = tuple(range(501, 517)) + tuple(range(601, 617)) + tuple(range(811, 819)) + tuple(range(1101, 1125))
SIMS = 20000


def extinct(path):
    p = json.loads(path.read_text(encoding="utf-8"))["pops"]
    return not (len(p) == 12 and p[-1] > 0)


def sign_p(saved, lost):
    n = saved + lost
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(comb(n, i) for i in range(min(saved, lost) + 1)) / 2 ** n)


def main():
    C = {s: extinct(EXP / "F1_baseline_fragility" / "output" / f"seed_{s}.json") for s in SEEDS}
    S = {s: extinct(EXP / "HB1_home_base" / "output" / f"s_seed_{s}.json") for s in SEEDS}
    S2 = {s: extinct(EXP / "MC1_moving_camp" / "output" / f"s_seed_{s}.json") for s in SEEDS}
    F2 = {s: extinct(EXP / "F2_perfect_search" / "output" / f"seed_{s}.json") for s in SEEDS}
    n = len(SEEDS)
    m = sum(C.values()) / n
    disc = sum(C[s] != S[s] for s in SEEDS) / n
    same_sham = all(S[s] == S2[s] for s in SEEDS)
    # two independent draws disagree with probability 2 E[q(1-q)] = disc
    eq1q = disc / 2
    var = m - eq1q - m * m
    k = m * (1 - m) / var - 1
    a, b = m * k, (1 - m) * k
    e_f2 = 1 - (sum(F2.values()) / n) / m
    L = ["# N8 — Power calculation (generated by `power_n8.py`)\n",
         f"Control (F1): {sum(C.values())} of {n} died out (m = {m:.3f}). Sham vs control: {round(disc * n)} of {n} worlds "
         f"changed fate (discordance {disc:.3f}); HB1's and MC1's shams identical: {'yes' if same_sham else 'NO'}.",
         f"Fitted spread of world-level extinction probability: Beta(a = {a:.3f}, b = {b:.3f}).",
         f"F2's effect (perfect partner finding): extinction {sum(F2.values())} of {n}, a relative reduction e = {e_f2:.2f}.\n",
         f"Power (share of {SIMS:,} simulated experiments with sign-test p < 0.05 and fewer extinctions in the treatment):\n",
         "| worlds | e = F2's (" + f"{e_f2:.2f}" + ") | half of F2's | a third of F2's |",
         "|---|---|---|---|"]
    rng = random.Random(8)
    for N in (64, 128, 192, 256):
        row = []
        for e in (e_f2, e_f2 / 2, e_f2 / 3):
            hits = 0
            for _ in range(SIMS):
                saved = lost = 0
                for _ in range(N):
                    q = rng.betavariate(a, b)
                    x = rng.random() < q
                    y = rng.random() < q * (1 - e)
                    if x and not y:
                        saved += 1
                    elif y and not x:
                        lost += 1
                if saved > lost and sign_p(saved, lost) < 0.05:
                    hits += 1
            row.append(f"{hits / SIMS:.2f}")
        L.append(f"| {N} | " + " | ".join(row) + " |")
    L.append("\nCheck: with e = 0 the same procedure gives the test's false-positive rate in the 'fewer' direction:")
    hits = 0
    for _ in range(SIMS):
        saved = lost = 0
        for _ in range(64):
            q = rng.betavariate(a, b)
            x, y = rng.random() < q, rng.random() < q
            saved += x and not y
            lost += y and not x
        hits += saved > lost and sign_p(saved, lost) < 0.05
    L.append(f"64 worlds, e = 0: {hits / SIMS:.3f} (should be at most about 0.025).")
    text = "\n".join(L) + "\n"
    (HERE / "power.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
