"""HF1 analysis with the frozen decision rule (questions.md, `HF1-questions`). Written before any data.

Operational details written with this file, before data:
- Fullness within 3 tiles of home: mean over couple-weeks of each couple home's mean (plants ÷ cap) on land tiles within
  `reach`, pooled over the set's worlds. H ÷ C is the ratio in the rule.
- Food per forage action: total `got` ÷ number of adult forage actions, pooled over the set. "Lower" means H < C.

  python experiments/HF1_home_food/analyse_hf1.py discovery   (or: holdout, or: both)
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from run_hf1 import DISCOVERY, HOLDOUT, OUT  # noqa: E402


def f(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def div(a, b):
    return a / b if b else None


def pooled(arm, seeds, out):
    n = Counter()
    R = []
    for s in seeds:
        r = json.loads((out / f"{arm}_seed_{s}.json").read_text(encoding="utf-8"))
        n.update(r["n"])
        R.append(r)
    return n, R


def section(name, seeds, out, L):
    w = L.append
    nh, RH = pooled("h", seeds, out)
    nc, RC = pooled("c", seeds, out)
    ok = all(r.get("reproduces") is not False and r["code_hash"] == r["code_hash_after"] for r in RH + RC)
    w(f"## {name} (seeds {seeds[0]}–{seeds[-1]}, first 40 years)\n")
    w(f"Replays reproduce saved runs (where saved) and code unchanged: **{'yes' if ok else 'NO'}**.\n")
    w("| seed | H population, years 10–40 | C population, years 10–40 |")
    w("|---|---|---|")
    for rh, rc in zip(RH, RC):
        w(f"| {rh['seed']} | {rh['pops']} | {rc['pops']} |")
    fh, fc = div(nh["full_in_sum"], nh["full_in_n"]), div(nc["full_in_sum"], nc["full_in_n"])
    gh, gc = div(nh["forage_got"], nh["forage_n"]), div(nc["forage_got"], nc["forage_n"])
    w("\n| measure | H (home base) | C (control) | H ÷ C |")
    w("|---|---|---|---|")
    rows = [("Q1 fullness within 3 tiles of home", fh, fc),
            ("Q1 fullness on the ring 4–6 tiles out", div(nh["full_ring_sum"], nh["full_ring_n"]),
             div(nc["full_ring_sum"], nc["full_ring_n"]))]
    for s, sn in enumerate(("spring", "summer", "autumn", "winter")):
        rows.append((f"Q1 fullness within 3 tiles, {sn}", div(nh[f"full_in_s{s}_sum"], nh[f"full_in_s{s}_n"]),
                     div(nc[f"full_in_s{s}_sum"], nc[f"full_in_s{s}_n"])))
    rows += [("Q2 food per adult forage action", gh, gc),
             ("Q2 food per forage action, within 3 tiles of home", div(nh["forage_near_got"], nh["forage_near_n"]),
              div(nc["forage_near_got"], nc["forage_near_n"])),
             ("Q2 food per forage action, further from home", div(nh["forage_far_got"], nh["forage_far_n"]),
              div(nc["forage_far_got"], nc["forage_far_n"])),
             ("Q2 food per forage action, forager without a couple home", div(nh["forage_nohome_got"], nh["forage_nohome_n"]),
              div(nc["forage_nohome_got"], nc["forage_nohome_n"])),
             ("Q2 share of forage actions leaving the tile with < 1 unit", div(nh["forage_emptied"], nh["forage_n"]),
              div(nc["forage_emptied"], nc["forage_n"])),
             ("Q2 share of adult forage actions within 3 tiles of home", div(nh["forage_near_n"], nh["forage_n"]),
              div(nc["forage_near_n"], nc["forage_n"])),
             ("Q3 people per land tile within 3 tiles of home", div(nh["load_sum"], nh["load_n"]),
              div(nc["load_sum"], nc["load_n"])),
             ("Q4 fullness around adults in their last 8 weeks before starving", div(nh["starved_full_sum"], nh["starved_n"]),
              div(nc["starved_full_sum"], nc["starved_n"])),
             ("Q4 fullness around all adults in the same weeks", div(nh["all_full_sum"], nh["starved_n"]),
              div(nc["all_full_sum"], nc["starved_n"])),
             ("hunts per person-year", div(nh["hunts"], nh["person_weeks"] / 52), div(nc["hunts"], nc["person_weeks"] / 52))]
    for lab, a, b in rows:
        w(f"| {lab} | {f(a)} | {f(b)} | {f(div(a, b)) if a is not None and b else '–'} |")
    w(f"\nCouple-weeks with a home: H {nh['couple_weeks']:,}, C {nc['couple_weeks']:,}. Adult forage actions: "
      f"H {nh['forage_n']:,}, C {nc['forage_n']:,}. Adult starvation deaths read: H {nh['starved_n']}, C {nc['starved_n']}.\n")
    return div(fh, fc), (gh is not None and gc is not None and gh < gc), ok


def main(which="both", out=OUT, write=True):
    L = ["# HF1 — Food around HB1's homes: results (generated by `analyse_hf1.py`)\n"]
    checks = (out / "checks.txt").read_text(encoding="utf-8")
    L.append(f"Observer read-only (H and C, two seeds): **{'yes' if 'CHANGES' not in checks and checks.count('READ-ONLY') >= 4 else 'NO'}**.\n")
    sets = [("discovery", DISCOVERY)] if which == "discovery" else [("holdout", HOLDOUT)] if which == "holdout" else \
        [("discovery", DISCOVERY), ("holdout", HOLDOUT)]
    res = {name: section(name, seeds, out, L) for name, seeds in sets}
    if len(res) == 2:
        (rd, ld, okd), (rh, lh, okh) = res["discovery"], res["holdout"]
        L.append("## Frozen decision rule\n")
        L.append(f"Fullness within 3 tiles of home, H ÷ C: discovery {f(rd)}, holdout {f(rh)}; food per forage action "
                 f"lower in H: discovery {'yes' if ld else 'no'}, holdout {'yes' if lh else 'no'}.\n")
        if rd is not None and rh is not None and rd <= 0.80 and rh <= 0.80 and ld and lh:
            v = "**Depletion confirmed** (present under HB1; causation not established, see Scope)."
        elif rd is not None and rh is not None and rd >= 0.90 and rh >= 0.90:
            v = "**Not confirmed.** The hunger has another cause; HB2 is not designed until it is found."
        else:
            v = "**Mixed / inconclusive.** Reported as such; the creator decides."
        L.append(v)
        if not (okd and okh):
            L.append("\n**A hard stop was hit: recorded, not interpreted.**")
    text = "\n".join(L) + "\n"
    if write:
        (HERE / f"results_{which}.md").write_text(text, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "both")
