"""H1 analysis in the frozen order (questions.md, `H1-questions`), with the frozen decision rule. Written before any data.

  python experiments/H1_partner_homes/analyse_h1.py
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from run_h1 import DISCOVERY, HOLDOUT, OUT  # noqa: E402


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "–"


def summarise(seeds, out):
    R = [json.loads((out / f"seed_{s}.json").read_text(encoding="utf-8")) for s in seeds]
    n = Counter()
    for r in R:
        n.update(r["n"])
    return R, n


def main(out=OUT, sets=(("discovery", DISCOVERY), ("holdout", HOLDOUT)), write=True):
    L = ["# H1 — Partners' homes: results (generated by `analyse_h1.py`)\n"]
    w = L.append
    checks = (out / "checks.txt").read_text(encoding="utf-8")
    w(f"Observer read-only: **{'yes' if 'CHANGES' not in checks and checks.count('READ-ONLY') >= 2 else 'NO'}**.\n")
    shares = {}
    for name, seeds in sets:
        R, n = summarise(seeds, out)
        rep = all(r["reproduces"] for r in R) and all(r["code_hash"] == r["code_hash_after"] for r in R)
        w(f"## {name} (seeds {seeds[0]}–{seeds[-1]}, 40 years)\n")
        w(f"Replays reproduce F1 and code unchanged: **{'yes' if rep else 'NO'}**. Population at years 10–40: "
          + "; ".join(f"{r['seed']} {r['pops']}" for r in R) + ".\n")
        cw, bh = n["couple_weeks"], n["both_home"]
        w(f"Couple-weeks: {cw:,}; apart {pct(n['apart'], cw)}; either partner without a home {pct(n['either_homeless'], cw)}.\n")
        w("**Q1. Distance between partners' homes** (couple-weeks where both have one):\n")
        w("| homes apart by | share |")
        w("|---|---|")
        for b in ("0-2", "3", "4-6", "7+"):
            w(f"| {b} tiles | {pct(n['homes|' + b], bh)} |")
        shares[name] = n["homes|0-2"] / bh if bh else 0.0
        pw = n["pos|at"] + n["pos|near"] + n["pos|away"]
        w(f"\n**Q2. Partners relative to their own homes:** at home {pct(n['pos|at'], pw)}, within 2 tiles "
          f"{pct(n['pos|near'], pw)}, further {pct(n['pos|away'], pw)}.\n")
        ah = n["apart_both_home"]
        w(f"**Q3. Apart couple-weeks** (both with homes, {ah:,}): both partners within 2 tiles of their own homes "
          f"{pct(n['apart_both_near_own_home'], ah)}; at least one away from home {pct(n['apart_one_away'], ah)}.\n")
        w(f"**Q4. Stability:** adults' homes changed in {pct(n['adult_home_changed'], n['adult_weeks'])} of adult-weeks; "
          f"adults without a home {pct(n['adult_homeless'], n['adult_weeks'])}.\n")
    w("## Frozen decision rule\n")
    d, h = shares.get("discovery", 0), shares.get("holdout", 0)
    if d >= 2 / 3 and h >= 2 / 3:
        verdict = "Homes already shared in effect: **L1 is the plausible smaller change**."
    elif d <= 1 / 3 and h <= 1 / 3:
        verdict = "Partners' homes are separate: **L2 (a shared home base) is needed** if co-residence is to be anchored."
    else:
        verdict = "**Mixed**; the creator decides."
    w(f"Partners' homes within 2 tiles: discovery {100 * d:.1f}%, holdout {100 * h:.1f}%. {verdict}")
    text = "\n".join(L) + "\n"
    if write:
        (HERE / "results.md").write_text(text, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
