"""Every number quoted in the paper draft, computed from the committed outputs of F1, F2 and C1 (rule 16).

    python paper/paper_numbers.py   -> paper/numbers.md
"""
from __future__ import annotations

import json
import statistics
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXP = ROOT / "experiments"
sys.path.insert(0, str(EXP / "F1_baseline_fragility"))
import analyse_f1 as A  # noqa: E402

DISC = A.DISCOVERY
HOLD = A.HOLDOUT
ALL = tuple(DISC) + tuple(HOLD)
L = []
w = L.append


def load(out, seeds):
    R = {}
    for s in seeds:
        r = json.loads((out / f"seed_{s}.json").read_text(encoding="utf-8"))
        r["Y"] = {int(k): v for k, v in r["years"].items()}
        r["extinct"] = not (len(r["pops"]) == 12 and r["pops"][-1] > 0)
        r["E"] = (r["final_tick"] - 1) // 52 if r["extinct"] else None
        R[s] = r
    return R


C = load(EXP / "F1_baseline_fragility" / "output", ALL)
P = load(EXP / "F2_perfect_search" / "output", ALL)

w("# Numbers quoted in the paper (generated by `paper_numbers.py`)\n")
w("## F1: baseline\n")
for name, seeds in (("discovery", DISC), ("holdout", HOLD), ("all", ALL)):
    ext = [s for s in seeds if C[s]["extinct"]]
    w(f"- {name}: died out {len(ext)} of {len(seeds)} ({len(ext) / len(seeds):.1%})")
ext = [C[s] for s in ALL if C[s]["extinct"]]
sur = [C[s] for s in ALL if not C[s]["extinct"]]
Es = sorted(r["E"] for r in ext)
gaps = sorted(r["E"] - max(b[0] for b in r["births"]) for r in ext)
Bs = sorted(max(b[0] for b in r["births"]) for r in ext)
w(f"- extinction years: min {Es[0]}, max {Es[-1]}, median {statistics.median(Es)}")
w(f"- last birth years: min {Bs[0]}, max {Bs[-1]}, median {statistics.median(Bs)}")
w(f"- years from last birth to extinction: min {gaps[0]}, max {gaps[-1]}, median {statistics.median(gaps)}")
peak = lambda rs: statistics.median(max(v.get("n", 0) for v in r["Y"].values()) for r in rs)
w(f"- peak population, median: extinct {peak(ext)}, survivors {peak(sur)}")
for lab, rs, win in (("survivors whole run", sur, lambda r: (0, 120)), ("survivors years 0-39", sur, lambda r: (0, 40)),
                     ("extinct whole life", ext, lambda r: (0, r["E"] + 1)),
                     ("extinct last 30 years", ext, lambda r: (max(0, r["E"] - 30), r["E"] + 1)),
                     ("extinct last 10 years", ext, lambda r: (max(0, r["E"] - 10), r["E"] + 1)),
                     ("survivors years 0-9", sur, lambda r: (0, 10)), ("extinct years 0-9", ext, lambda r: (0, 10))):
    t = A.rates(None, [(r, *win(r)) for r in rs])
    w(f"- {lab}: births/woman-yr {A.fmt(t['births_per_woman_year'])}, deaths/person-yr {A.fmt(t['deaths_per_person_year'])}, "
      f"child deaths/birth {A.fmt(t['child_deaths_per_birth'])}, starving share {A.fmt(t['starving_share'])}, "
      f"no-partner share {A.fmt(t['block_no_partner'])}, pairs/person-yr {A.fmt(t['pairs_per_person_year'])}, "
      f"old age share of deaths {A.fmt(t['cause_old age'])}, starvation share of deaths {A.fmt(t['cause_starvation'])}")
for lab, rs, win in (("survivors years 10-39", sur, lambda r: (10, 40)), ("extinct years 10-39", ext, lambda r: (10, min(40, r["E"] + 1)))):
    t = A.rates(None, [(r, *win(r)) for r in rs])
    w(f"- {lab}: pairs/person-yr {A.fmt(t['pairs_per_person_year'])}")
ma = lambda rs, y0, y1: statistics.mean(r["Y"][y]["mean_age"] for r in rs for y in range(y0(r), y1(r)) if y in r["Y"] and "mean_age" in r["Y"][y])
w(f"- mean age: extinct last 10 y {ma(ext, lambda r: max(0, r['E'] - 10), lambda r: r['E'] + 1):.1f}; survivors whole run {ma(sur, lambda r: 0, lambda r: 120):.1f}")
au = lambda rs, y: statistics.median(statistics.mean(r["Y"][k]["autumn_tile"] for k in range(y - 10, y) if "autumn_tile" in r["Y"].get(k, {})) for r in rs)
w(f"- autumn food per land tile, years 30-39, median of worlds: future-extinct {au([r for r in ext if r['E'] >= 60], 40):.1f}, survivors {au(sur, 40):.1f}")


def auc(pos, neg):
    s = sum(1.0 if a > b else 0.5 if a == b else 0.0 for a in pos for b in neg)
    return s / (len(pos) * len(neg))


w("\n## F1: early warning (AUC separation; all 64 worlds pooled, and per set)\n")
for t in (20, 30, 40):
    for k in ("population", "women 16-45", "share of women 16-45 unpartnered", "births per woman-year, past decade",
              "starving share, past decade", "autumn food per land tile, past decade"):
        row = []
        for name, seeds in (("disc", DISC), ("hold", HOLD), ("all", ALL)):
            fe = [C[s] for s in seeds if C[s]["extinct"] and C[s]["E"] >= t + 20]
            sv = [C[s] for s in seeds if not C[s]["extinct"]]
            u = auc([A.indicators(r, t)[k] for r in fe], [A.indicators(r, t)[k] for r in sv])
            row.append(f"{name} {max(u, 1 - u):.2f}")
        w(f"- year {t}, {k}: " + ", ".join(row))
at30 = [C[s] for s in ALL if C[s]["Y"].get(30, {}).get("n", 0) > 0]
g1e = sum(1 for r in at30 if r["extinct"] and r["Y"][30]["n"] < 20)
g1s = sum(1 for r in at30 if not r["extinct"] and r["Y"][30]["n"] < 20)
g7e = sum(1 for r in at30 if r["extinct"] and r["Y"][30].get("women", 0) <= 3)
g7s = sum(1 for r in at30 if not r["extinct"] and r["Y"][30].get("women", 0) <= 3)
ne, ns = sum(r["extinct"] for r in at30), sum(not r["extinct"] for r in at30)
w(f"- year 30, population < 20: extinct {g1e} of {ne}, survivors {g1s} of {ns}")
w(f"- year 30, at most 3 women 16-45: extinct {g7e} of {ne}, survivors {g7s} of {ns}")

w("\n## F1: mates within sight (single women 16-45, mid-year snapshots)\n")
for lab, rs, y0, y1 in (("survivors 0-39", sur, 0, 40), ("survivors 40-119", sur, 40, 120), ("extinct all", ext, 0, 120)):
    ws = sum(r["Y"].get(y, {}).get("women_single", 0) for r in rs for y in range(y0, y1))
    wn = sum(r["Y"].get(y, {}).get("women_single_no_mate_near", 0) for r in rs for y in range(y0, y1))
    wf = sum(r["Y"].get(y, {}).get("women_single_no_mate", 0) for r in rs for y in range(y0, y1))
    w(f"- {lab}: {ws} single-woman-years; none eligible within sight {wn / ws:.0%}; none in world {wf / ws:.0%}")

w("\n## F2: perfect partner finding\n")
dc, dp = sum(r["extinct"] for r in C.values()), sum(r["extinct"] for r in P.values())
saved = [s for s in ALL if C[s]["extinct"] and not P[s]["extinct"]]
lost = [s for s in ALL if not C[s]["extinct"] and P[s]["extinct"]]
both = [s for s in ALL if C[s]["extinct"] and P[s]["extinct"]]
w(f"- died out: F1 {dc} of 64, F2 {dp} of 64; saved {len(saved)}, lost {len(lost)} {lost}, die either way {len(both)} {both}")
for name, R in (("F1", C), ("F2", P)):
    n = Counter()
    for r in R.values():
        for v in r["Y"].values():
            n.update({k: x for k, x in v.items() if k in ("woman_weeks", "r_no_partner")})
    t = A.rates(None, [(r, 0, (r["E"] + 1) if r["extinct"] else 120) for r in R.values()])
    pops = {y: statistics.median(r["Y"].get(y, {}).get("n", 0) for r in R.values()) for y in (40, 80, 119)}
    w(f"- {name}: no-partner share of woman-weeks {n['r_no_partner'] / n['woman_weeks']:.3f}; births/woman-yr "
      f"{A.fmt(t['births_per_woman_year'])}; child deaths/birth {A.fmt(t['child_deaths_per_birth'])}; starving share "
      f"{A.fmt(t['starving_share'])}; starvation share of deaths {A.fmt(t['cause_starvation'])}; median pop "
      + ", ".join(f"y{y} {v:.0f}" for y, v in pops.items()))
dying = [P[s] for s in ALL if P[s]["extinct"]]
ws = sum(v.get("women_single", 0) for r in dying for v in r["Y"].values())
wf = sum(v.get("women_single_no_mate", 0) for r in dying for v in r["Y"].values())
w(f"- F2 dying worlds: single-woman-years {ws}, with no eligible man anywhere {wf}")
w(f"- F2 dying worlds, population at year 10: {sorted(r['Y'].get(10, {}).get('n', 0) for r in dying)}")
w(f"- extinction delayed (F1 -> F2) in worlds dying either way: {[(s, C[s]['E'], P[s]['E']) for s in both]}")
td = A.rates(None, [(r, 0, r["E"] + 1) for r in dying])
ts = A.rates(None, [(r, 0, 120) for r in P.values() if not r["extinct"]])
w(f"- F2 child deaths/birth: dying {A.fmt(td['child_deaths_per_birth'])}, surviving {A.fmt(ts['child_deaths_per_birth'])}")

w("\n## C1: couples apart (from its results files)\n")
for name in ("discovery", "holdout"):
    n = Counter()
    for s in (range(501, 517) if name == "discovery" else range(1101, 1117)):
        n.update(json.loads((EXP / "C1_couples_apart" / "output" / f"seed_{s}.json").read_text(encoding="utf-8"))["n"])
    ap = n["apart"]
    tot = sum(v for k, v in n.items() if k.startswith("split_action|"))
    w(f"- {name}: apart {ap / n['couple_weeks']:.1%} of {n['couple_weeks']} couple-weeks; at exactly 3 tiles "
      f"{n['dist|3'] / ap:.1%}; splits by foraging {n['split_action|forage'] / tot:.1%}; beyond reach join in top-4 "
      f"{n['beyond_join_top4'] / n['beyond_pw']:.1%}, chosen {n['beyond_chosen|join'] / n['beyond_pw']:.1%}, forage chosen "
      f"{n['beyond_chosen|forage'] / n['beyond_pw']:.1%}")

text = "\n".join(L) + "\n"
(Path(__file__).parent / "numbers.md").write_text(text, encoding="utf-8")
sys.stdout.reconfigure(encoding="utf-8")
print(text)
